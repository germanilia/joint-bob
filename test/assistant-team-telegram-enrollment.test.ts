import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { teamDatabase, createTeam, prepareTeamProject } from '../src/assistant-teams/store.js';
import { requireClusterMember, requireTeamMember } from '../src/assistant-teams/access.js';
import { getClusterNode } from '../src/cluster.js';
import { createAdministrator, createLocalUser, localAccountIdForUsername, type AuthSession } from '../src/auth.js';
import { createMembershipCluster } from '../src/cluster-membership.js';
import { addClusterLocalMember, removeClusterLocalMember } from '../src/cluster-accounts.js';
import { issueTeamEnrollment, redeemTeamEnrollment, confirmTeamEnrollment, issueTeamGroupChallenge, redeemTeamGroupChallenge, confirmTeamGroup, authorizeTeamTelegram } from '../src/assistant-teams/telegram.js';
import { telegramDatabase, saveTeamTelegramConnection, teamTelegramHeaderValid } from '../src/assistant-teams/telegram-store.js';

test('enrollment is expiring, single-use, pending until same-account confirmation; groups require confirmation', async () => {
 const db = await teamDatabase(), host = await getClusterNode();
 createAdministrator('enrollment', 'Synthetic-password-123!', false);
 const accountId = localAccountIdForUsername('enrollment')!;
 const session: AuthSession = { id: randomUUID(), userId: randomUUID(), accountId, username:'enrollment', homeNodeId:null, isRemoteLogin:false, email:null, role:'admin', csrfToken:'fixture', mustChangePassword:false };
 const clusterId = randomUUID();
 createMembershipCluster(db, {nodeId:host.id,name:'host',url:'http://127.0.0.1:19001'}, {id:clusterId,name:'fixture'});
 addClusterLocalMember(db,clusterId,accountId);
 const actor = await requireClusterMember(session,clusterId);
 const team = await createTeam(actor,{projectId:await prepareTeamProject(actor),executorAccountId:accountId});
 const member = await requireTeamMember(session,team.id);
 await telegramDatabase();
 saveTeamTelegramConnection(db,{teamId:team.id,botId:'123',botUsername:'fixture_bot',tokenAccountId:'fixture',headerSecret:'secret',readsAllGroupMessages:true});
 assert.equal(await teamTelegramHeaderValid(team.id,'forged'),false);assert.equal(await teamTelegramHeaderValid(team.id,'secret'),true);
 const link = await issueTeamEnrollment(member); const code = new URL(link.link).searchParams.get('start')!;
 assert.ok(Math.abs(Date.parse(link.expiresAt)-Date.now()-600000)<1000);
 assert.ok(!JSON.stringify(db.prepare('SELECT * FROM assistant_team_telegram_challenges').all()).includes(code));
 const outcomes=await Promise.allSettled([redeemTeamEnrollment(code,{id:'7',name:'human'}),redeemTeamEnrollment(code,{id:'8',name:'forwarded'})]);
 assert.equal(outcomes.filter(r=>r.status==='fulfilled').length,1);
 await assert.rejects(authorizeTeamTelegram(team.id,'-1','7'));
 await assert.rejects(confirmTeamEnrollment({...member,accountId:'wrong'},link.id));
 createLocalUser({username:'remaining',email:'remaining@example.invalid'});const remaining=localAccountIdForUsername('remaining')!;addClusterLocalMember(db,clusterId,remaining);
 const other=await requireTeamMember({...session,accountId:remaining,username:'remaining'},team.id);await assert.rejects(confirmTeamEnrollment(other,link.id));
 await confirmTeamEnrollment(member,link.id);
 await assert.rejects(confirmTeamEnrollment(member,link.id));
 const group=await issueTeamGroupChallenge(member);
 await redeemTeamGroupChallenge(team.id,group.code,'-1','7');
 await assert.rejects(authorizeTeamTelegram(team.id,'-1','7'));
 await confirmTeamGroup(member,group.id);
 assert.equal((await authorizeTeamTelegram(team.id,'-1','7')).accountId,accountId);
 await assert.rejects(authorizeTeamTelegram(team.id,'-2','7'));
 await assert.rejects(authorizeTeamTelegram(team.id,'-1','8'));
 const expired=await issueTeamEnrollment(member);
 db.prepare('UPDATE assistant_team_telegram_challenges SET expires_at=0 WHERE id=?').run(expired.id);
 await assert.rejects(redeemTeamEnrollment(new URL(expired.link).searchParams.get('start')!,{id:'9',name:'late'}));
 assert.throws(()=>saveTeamTelegramConnection(db,{teamId:'other',botId:'123',botUsername:'fixture_bot',tokenAccountId:'x',headerSecret:'x',readsAllGroupMessages:true}));
 const {ensureTelegramSchema,saveTelegramConnection,telegramBotIsBobs}=await import('../src/control-center/telegram-store.js');
 ensureTelegramSchema(db);saveTelegramConnection(db,{accountId,tokenAccountId:'private',botId:'999',botUsername:'private',urlSecret:'private-url',headerSecret:'private-header'});
 assert.throws(()=>saveTeamTelegramConnection(db,{teamId:'other',botId:'999',botUsername:'private',tokenAccountId:'x',headerSecret:'x',readsAllGroupMessages:true}));
 assert.equal(telegramBotIsBobs(db,'123'),true);
 const {telegramBotInUse}=await import('../src/assistant-telegram.js');assert.equal(telegramBotInUse(db,'123'),true);assert.equal(telegramBotInUse(db,'999'),true);
 const replacement=await issueTeamEnrollment(member);await redeemTeamEnrollment(new URL(replacement.link).searchParams.get('start')!,{id:'10',name:'replacement'});await confirmTeamEnrollment(member,replacement.id);
 await assert.rejects(authorizeTeamTelegram(team.id,'-1','7'));assert.equal((await authorizeTeamTelegram(team.id,'-1','10')).accountId,accountId);
 removeClusterLocalMember(db,clusterId,accountId);await assert.rejects(authorizeTeamTelegram(team.id,'-1','10'));
});
