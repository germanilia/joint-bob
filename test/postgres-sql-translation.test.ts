import assert from "node:assert/strict";
import test from "node:test";
import { planStatement, splitStatements, tokenize, type Plan, type SchemaLookup } from "../src/postgres/sql-translation.js";

const schema: SchemaLookup = {
  table: (name) => (name === "settings" ? { columns: ["key", "value", "updated_at"], uniqueKeys: [["key"]] } : undefined),
};

function plan(sql: string): Plan {
  const [statement, ...rest] = splitStatements(tokenize(sql));
  assert.equal(rest.length, 0);
  return planStatement(statement, schema);
}
function text(sql: string): string {
  const planned = plan(sql);
  assert.equal(planned.kind, "query");
  return (planned as Extract<Plan, { kind: "query" }>).query.text;
}

test("parameters become numbered and keep their SQLite argument positions", () => {
  const planned = plan("SELECT * FROM t WHERE a = ? AND b = ?2 AND c = ? AND d = '?'") as Extract<Plan, { kind: "query" }>;
  assert.equal(planned.query.text, "SELECT * FROM t WHERE a = $1 AND b = $2 AND c = $3 AND d = '?'");
  assert.deepEqual(planned.query.args, [0, 1, 2]);
});

test("SQLite expressions become their PostgreSQL equivalents", () => {
  assert.equal(text("SELECT x FROM t WHERE thread IS ? AND other IS NOT ? AND gone IS NULL"), "SELECT x FROM t WHERE thread IS NOT DISTINCT FROM $1 AND other IS DISTINCT FROM $2 AND gone IS NULL");
  assert.equal(text("SELECT name FROM t WHERE name LIKE ? COLLATE NOCASE"), 'SELECT name FROM t WHERE name ILIKE $1 COLLATE "nocase"');
  assert.equal(text("UPDATE t SET seen = MAX(seen, ?), n = max(n)"), "UPDATE t SET seen = sqlite_max(seen, $1), n = max(n)");
  assert.equal(text("SELECT ifnull(a, 0), instr(b, 'x'), CAST(c AS INTEGER) FROM t WHERE id IN ()"), "SELECT coalesce(a, 0), strpos(b, 'x'), CAST(c AS BIGINT) FROM t WHERE id IN (SELECT NULL WHERE FALSE)");
});

test("names keep their case, and names PostgreSQL reserves stay names", () => {
  assert.equal(text("SELECT sessionId, created_at AS createdAt, user FROM `browser_sessions` WHERE [profileId] = ?"), 'SELECT "sessionId", created_at AS "createdAt", "user" FROM "browser_sessions" WHERE "profileId" = $1');
});

test("INSERT OR IGNORE and OR REPLACE resolve conflicts the way SQLite does", () => {
  assert.equal(text("INSERT OR IGNORE INTO settings (key, value) VALUES (?, ?)"), "INSERT INTO settings (key, value) VALUES ($1, $2) ON CONFLICT DO NOTHING");
  assert.equal(text("INSERT OR REPLACE INTO settings VALUES (?, ?, ?)"), 'INSERT INTO settings ("key", "value", "updated_at") VALUES ($1, $2, $3) ON CONFLICT ("key") DO UPDATE SET "value" = EXCLUDED."value", "updated_at" = EXCLUDED."updated_at"');
  assert.equal(text("REPLACE INTO settings (key, value) VALUES (?, ?) RETURNING key"), 'INSERT INTO settings (key, value) VALUES ($1, $2) ON CONFLICT ("key") DO UPDATE SET "value" = EXCLUDED."value" RETURNING key');
});

test("CREATE TABLE maps SQLite types and adds the rowid SQLite keeps", () => {
  const planned = plan("CREATE TABLE IF NOT EXISTS jobs (id TEXT PRIMARY KEY, attempts INTEGER NOT NULL DEFAULT 0, score REAL, body BLOB, ownerId TEXT COLLATE NOCASE, UNIQUE(ownerId) ON CONFLICT REPLACE) WITHOUT ROWID") as Extract<Plan, { kind: "query" }>;
  assert.equal(planned.query.text, 'CREATE TABLE IF NOT EXISTS jobs (id TEXT COLLATE "C" PRIMARY KEY, attempts BIGINT NOT NULL DEFAULT 0, score DOUBLE PRECISION, body BYTEA, "ownerId" TEXT COLLATE "nocase", UNIQUE ( "ownerId" )); SELECT sqlite_install_references()');
  assert.deepEqual(planned.change, { op: "create", type: "table", name: "jobs", table: "jobs", sql: "CREATE TABLE jobs (id TEXT PRIMARY KEY, attempts INTEGER NOT NULL DEFAULT 0, score REAL, body BLOB, ownerId TEXT COLLATE NOCASE, UNIQUE(ownerId) ON CONFLICT REPLACE) WITHOUT ROWID", ifNotExists: true });
  assert.equal(text("CREATE TABLE log (at TEXT NOT NULL)"), 'CREATE TABLE log (at TEXT COLLATE "C" NOT NULL, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE); SELECT sqlite_install_references()');
  assert.equal(text("CREATE TABLE counters (id INTEGER PRIMARY KEY AUTOINCREMENT, n INTEGER)"), "CREATE TABLE counters (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, n BIGINT); SELECT sqlite_install_references()");
});

test("transaction statements and pragmas are planned, not sent as they are", () => {
  assert.deepEqual(plan("BEGIN IMMEDIATE"), { kind: "transaction", op: "beginImmediate" });
  assert.deepEqual(plan("ROLLBACK TO project_create"), { kind: "transaction", op: "rollbackTo", name: "project_create" });
  assert.deepEqual(plan("RELEASE SAVEPOINT project_create"), { kind: "transaction", op: "release", name: "project_create" });
  assert.deepEqual(plan("PRAGMA busy_timeout = 5000"), { kind: "rows", rows: [] });
  assert.equal(text("PRAGMA table_info(browser_sessions)"), "SELECT * FROM pragma_table_info('browser_sessions')");
});

test("a trigger's body stays one statement and becomes a trigger function", () => {
  const statements = splitStatements(tokenize("CREATE TRIGGER IF NOT EXISTS bump AFTER UPDATE OF epoch ON live WHEN OLD.epoch IS NOT NEW.epoch BEGIN UPDATE rev SET value = value + 1 WHERE id = 1; END; SELECT 1"));
  assert.equal(statements.length, 2);
  const planned = planStatement(statements[0], schema) as Extract<Plan, { kind: "query" }>;
  assert.match(planned.query.text, /CREATE OR REPLACE FUNCTION "bump_fn"\(\) RETURNS trigger/);
  assert.match(planned.query.text, /CREATE TRIGGER bump AFTER UPDATE OF epoch ON live FOR EACH ROW WHEN \(OLD \. epoch IS DISTINCT FROM NEW \. epoch\) EXECUTE FUNCTION "bump_fn"\(\)/);
});

test("UPDATE OR IGNORE updates row by row so a conflicting row is skipped", () => {
  const planned = plan("UPDATE OR IGNORE owners SET account_id = ? WHERE account_id = ?");
  assert.deepEqual(planned, {
    kind: "updateOrIgnore", tables: ["owners"],
    select: { text: "SELECT rowid FROM owners WHERE account_id = $1", args: [1] },
    update: { text: "UPDATE owners SET account_id = $1 WHERE rowid = $2", args: [0, 2] },
  });
});

test("a bare column in ON CONFLICT DO UPDATE means the existing row, as in SQLite", () => {
  assert.equal(
    text("INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value = max(value, excluded.value), updated_at = ? WHERE value < excluded.value"),
    "INSERT INTO settings (key, value) VALUES ($1, $2) ON CONFLICT(key) DO UPDATE SET value = sqlite_max(settings.value, excluded.value), updated_at = $3 WHERE settings.value < excluded.value",
  );
});

test("json_extract keeps the JSON value's type where the caller sees it", () => {
  assert.equal(
    text("SELECT json_extract(payload, '$.cost') cost, COALESCE(json_extract(payload, '$.input'), 0) + 1 AS input FROM usage WHERE json_extract(payload, '$.kind') = ?"),
    "SELECT sqlite_json_typed(payload, '$.cost') AS cost, COALESCE(sqlite_json_number(payload, '$.input'), 0) + 1 AS input FROM usage WHERE json_extract(payload, '$.kind') = $1",
  );
  assert.equal(text("INSERT INTO settings (key) SELECT json_extract(payload, '$.kind') FROM usage"), "INSERT INTO settings (key) SELECT json_extract(payload, '$.kind') FROM usage");
});

test("SELECT DISTINCT ordered by an expression groups by its columns instead", () => {
  assert.equal(
    text("SELECT DISTINCT p.kind,p.resource_id FROM policy p WHERE p.deleted=0 ORDER BY CASE p.kind WHEN 'project' THEN 0 ELSE 1 END,p.resource_id"),
    "SELECT p.kind,p.resource_id FROM policy p WHERE p.deleted=0 GROUP BY p.kind, p.resource_id ORDER BY CASE p.kind WHEN 'project' THEN 0 ELSE 1 END,p.resource_id",
  );
  assert.equal(text("SELECT grant.scope FROM grants grant"), 'SELECT "grant".scope FROM grants "grant"');
});

test("references keep SQLite's lenient checks and their ON DELETE action", () => {
  const created = text("CREATE TABLE sessions (id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE, project TEXT REFERENCES projects(id), FOREIGN KEY(kind, resource_id) REFERENCES policy(kind, resource_id))");
  assert.equal(created.split("; ")[0], 'CREATE TABLE sessions (id TEXT COLLATE "C" PRIMARY KEY, user_id TEXT COLLATE "C" NOT NULL, project TEXT COLLATE "C", rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE)');
  assert.match(created, /CREATE OR REPLACE TRIGGER "sqlite_fk_sessions_user_id" AFTER DELETE ON users FOR EACH ROW/);
  assert.match(created, /DELETE FROM sessions WHERE user_id = OLD\.id/);
  assert.doesNotMatch(created, /projects|policy/);
});

test("a grouped query's bare columns are read from one of the group's rows", () => {
  assert.equal(
    text("SELECT m.node_id id,COALESCE(e.name,m.node_id) name, count(*) AS n FROM memberships m LEFT JOIN endpoints e ON e.node_id=m.node_id GROUP BY m.node_id ORDER BY name"),
    "SELECT m.node_id AS id, min(COALESCE(e.name,m.node_id)) AS name, count(*) AS n FROM memberships m LEFT JOIN endpoints e ON e.node_id=m.node_id GROUP BY m.node_id ORDER BY name",
  );
});

test("result columns get AS, grouped aliases count as grouped, and 0/1 conditions become booleans", () => {
  assert.equal(
    text("SELECT substr(e.occurred_at,1,16) minute, COUNT(*) requests FROM events e WHERE 1=1 AND 0 GROUP BY minute"),
    "SELECT substr(e.occurred_at,1,16) AS minute, COUNT(*) AS requests FROM events e WHERE 1=1 AND FALSE GROUP BY minute",
  );
  assert.equal(text("SELECT id, name FROM t WHERE NOT deleted"), "SELECT id, name FROM t WHERE NOT deleted");
});

test("a WITH query's own result columns get AS too", () => {
  assert.equal(
    text("WITH s AS (SELECT at FROM obs) SELECT CASE WHEN at='' THEN 'undated' ELSE substr(at,1,10) END day, COUNT(*) replies FROM s GROUP BY day"),
    "WITH s AS (SELECT at FROM obs) SELECT CASE WHEN at='' THEN 'undated' ELSE substr(at,1,10) END AS day, COUNT(*) AS replies FROM s GROUP BY day",
  );
});

test("columns grouped by position are not read through min()", () => {
  assert.equal(text("SELECT substr(at,1,10) day, model m, COUNT(*) n FROM obs GROUP BY 1,2"), "SELECT substr(at,1,10) AS day, model AS m, COUNT(*) AS n FROM obs GROUP BY 1,2");
});

test("json_group_array is cast to text so json_each can read it back", () => {
  assert.equal(text("SELECT json_group_array(json_object('a', x)) FROM t"), "SELECT (json_agg(json_build_object('a', x)))::TEXT FROM t");
});

test("the numbers the answer cache reads between writes are planned", () => {
  assert.deepEqual(plan("SELECT total_changes() AS c"), { kind: "totalChanges", column: "c" });
  assert.deepEqual(plan("SELECT total_changes()"), { kind: "totalChanges", column: "total_changes()" });
  assert.equal(text("PRAGMA data_version"), "SELECT value AS data_version FROM sqlite_pragma WHERE name = 'data_version'");
});
