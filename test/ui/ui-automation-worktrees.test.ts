import assert from "node:assert/strict";
import test from "node:test";
import { nativeUiFixture } from "./native-ui-fixture.js";

test("webhook and schedule editors default to worktrees and persist the per-item opt-out", { timeout: 180_000 }, async t => {
  const { page, environment, node } = await nativeUiFixture(t);
  await page.goto(node.url);
  await page.locator("#loginDialog[open]").waitFor();
  await page.getByTestId("login-username-input").fill(environment.username);
  await page.getByTestId("login-password-input").fill(environment.password);
  await page.getByTestId("login-submit-button").click();
  await page.waitForFunction(() => document.querySelectorAll("#projectList .list-row").length === 3);
  await page.locator('[aria-label="Actions for Internal Assistant"]').click();
  await page.getByTestId("project-cron-button").click();
  await page.waitForFunction(() => document.querySelector<HTMLSelectElement>('[data-testid="cron-owner"]')!.options.length > 0);
  await page.getByTestId("cron-new").click();
  assert.equal(await page.getByTestId("cron-run-in-worktree").isChecked(), true);
  await page.getByTestId("cron-name").fill("Isolated schedule");
  await page.getByTestId("cron-prompt").fill("Check the project");
  await page.getByTestId("cron-enabled").uncheck();
  await page.getByTestId("cron-run-in-worktree").uncheck();
  await page.getByTestId("cron-save").click();
  await page.getByTestId("cron-edit").waitFor();
  await page.getByTestId("cron-edit").click();
  assert.equal(await page.getByTestId("cron-run-in-worktree").isChecked(), false);
  await page.getByTestId("cron-run-in-worktree").check();
  await page.getByTestId("cron-save").click();
  await page.getByTestId("cron-edit").waitFor();
  await page.getByTestId("cron-edit").click();
  assert.equal(await page.getByTestId("cron-run-in-worktree").isChecked(), true);
  await page.getByTestId("cron-cancel").click();
  await page.getByTestId("cron-close").click();

  await page.getByTestId("settings-open-button").click();
  await page.getByTestId("settings-tab-webhooks").click();
  await page.waitForFunction(() => document.querySelector<HTMLSelectElement>("#webhooksOwner")!.options.length > 0 && document.querySelector<HTMLSelectElement>("#webhooksProject")!.options.length > 0);
  await page.getByTestId("webhooks-new-button").click();
  await page.getByTestId("webhooks-form").waitFor({ state: "visible" });
  await page.getByTestId("webhooks-name-input").fill("Isolated webhook");
  await page.getByTestId("webhooks-tab-access").click();
  await page.locator('[data-webhook-panel="access"]:not([inert])').waitFor();
  assert.equal(await page.getByTestId("webhooks-run-in-worktree-toggle").isChecked(), true);
  assert.equal(await page.getByTestId("webhooks-preserve-files-toggle").isDisabled(), true);
  await page.getByTestId("webhooks-enabled-toggle").uncheck();
  await page.getByTestId("webhooks-run-in-worktree-toggle").uncheck();
  assert.equal(await page.getByTestId("webhooks-preserve-files-toggle").isDisabled(), false);
  await page.getByTestId("webhooks-save-button").click();
  await page.getByTestId("webhooks-reveal").waitFor({ state: "visible" });
  await page.getByTestId("webhooks-reveal-done-button").click();
  await page.waitForFunction(() => !document.querySelector<HTMLButtonElement>("#webhooksSave")!.disabled);
  await page.getByTestId("webhooks-back-button").click();
  await page.getByTestId("webhooks-open-button").click();
  await page.getByTestId("webhooks-form").waitFor({ state: "visible" });
  await page.getByTestId("webhooks-tab-access").click();
  await page.locator('[data-webhook-panel="access"]:not([inert])').waitFor();
  assert.equal(await page.getByTestId("webhooks-run-in-worktree-toggle").isChecked(), false);
  await page.getByTestId("webhooks-run-in-worktree-toggle").check();
  await page.getByTestId("webhooks-save-button").click();
  await page.getByTestId("webhooks-savebar").waitFor({ state: "hidden" });
  await page.waitForFunction(() => !document.querySelector<HTMLButtonElement>("#webhooksSave")!.disabled);
  await page.getByTestId("webhooks-back-button").click();
  await page.getByTestId("webhooks-open-button").click();
  await page.getByTestId("webhooks-form").waitFor({ state: "visible" });
  await page.getByTestId("webhooks-tab-access").click();
  await page.locator('[data-webhook-panel="access"]:not([inert])').waitFor();
  assert.equal(await page.getByTestId("webhooks-run-in-worktree-toggle").isChecked(), true);
});
