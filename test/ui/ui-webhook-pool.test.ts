import assert from "node:assert/strict";
import test from "node:test";
import { nativeUiFixture } from "./native-ui-fixture.js";
import { api, signIn } from "../dev-nodes.js";

test("webhook saves and restores pool and Guardian bypass", { timeout: 120_000 }, async t => {
  const { page, environment, node } = await nativeUiFixture(t);
  const auth = await signIn(environment, node);
  const profile = await api<{ profile: { id: string } }>(node, auth, "POST", "/provider-profiles", { label: "Synthetic", provider: "claude" });
  assert.equal(profile.status, 201);
  const pool = await api<{ pool: { id: string } }>(node, auth, "POST", "/provider-profiles/pools", { name: "Webhook pool", profileIds: [profile.body.profile.id] });
  assert.equal(pool.status, 201);
  await page.goto(node.url);
  await page.locator("#loginDialog[open]").waitFor();
  await page.locator("#loginUsernameInput").fill(environment.username);
  await page.locator("#loginPasswordInput").fill(environment.password);
  await page.locator("#loginSubmitButton").click();
  if (await page.getByTestId("bob-head-app-settings").isVisible()) await page.getByTestId("bob-head-app-settings").click();
  else await page.getByTestId("settings-open-button").click();
  await page.getByTestId("settings-tab-webhooks").click();
  await page.waitForFunction(() => (document.querySelector("#webhooksProject") as HTMLSelectElement).options.length > 0 && !(document.querySelector("#webhooksNew") as HTMLButtonElement).disabled);
  await page.getByTestId("webhooks-new-button").click();
  const picker = page.getByTestId("webhooks-provider-pool");
  await page.waitForFunction(() => !(document.querySelector('[data-testid="webhooks-provider-pool"]') as HTMLSelectElement).disabled);
  await picker.selectOption(pool.body.pool.id);
  await page.getByTestId("webhooks-name-input").fill("Pool webhook");
  await page.getByTestId("webhooks-tab-access").click();
  await page.locator("#webhooksBypassGuardian").check();
  await page.getByTestId("webhooks-save-button").click();
  await page.getByTestId("webhooks-reveal").waitFor({ state: "visible" });
  await page.getByTestId("webhooks-reveal-done-button").click();
  await page.getByTestId("webhooks-back-button").click();
  await page.getByTestId("webhooks-open-button").click();
  await page.waitForFunction(() => !(document.querySelector('[data-testid="webhooks-provider-pool"]') as HTMLSelectElement).disabled);
  assert.equal(await picker.inputValue(), pool.body.pool.id);
  await page.getByTestId("webhooks-tab-access").click();
  assert.equal(await page.locator("#webhooksBypassGuardian").isChecked(), true);
});
